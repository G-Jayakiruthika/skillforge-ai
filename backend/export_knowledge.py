"""
export_knowledge.py - writes frontend/js/knowledge.js from skillforge/knowledge.py
so the browser-only web version uses exactly the same knowledge base.

Run after editing knowledge.py:   python export_knowledge.py
(tests/test_engine.py fails if the two get out of sync)
"""
import json
from pathlib import Path

from skillforge import institutions as inst
from skillforge import knowledge as k

OUT = Path(__file__).resolve().parent.parent / "frontend" / "js" / "knowledge.js"


def build() -> str:
    data = {
        "SYNONYMS": k.SYNONYMS, "ESCO_CODES": k.ESCO_CODES, "PREREQUISITES": k.PREREQUISITES,
        "ROLE_BENCHMARKS": k.ROLE_BENCHMARKS, "ROLE_DESCRIPTIONS": k.ROLE_DESCRIPTIONS,
        "LEVEL_SCORES": k.LEVEL_SCORES, "MASTERY_PASS": k.MASTERY_PASS, "WORKING_LEVEL": k.WORKING_LEVEL,
        "SKILLS": k.SKILLS, "INDUSTRIES": k.INDUSTRIES, "COMPANIES": k.COMPANIES, "COMPANY_NOTE": k.COMPANY_NOTE,
        "ROLE_INDUSTRY": k.ROLE_INDUSTRY,
        "PRIVACY_CATEGORIES": __import__("skillforge.service", fromlist=["x"]).PRIVACY_CATEGORIES,
        "DATA_WE_KEEP": __import__("skillforge.service", fromlist=["x"]).DATA_WE_KEEP,
        "INSTITUTIONS": inst.all_institutions(), "GEOGRAPHY": inst.geography(),
        "KIND_LABELS": inst.KIND_LABELS, "INSTITUTION_NOTE": inst.SOURCE_NOTE,
    }
    return ("// AUTO-GENERATED by backend/export_knowledge.py - do not edit by hand.\n"
            "export default " + json.dumps(data, indent=1, ensure_ascii=False) + ";\n")


if __name__ == "__main__":
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(build(), encoding="utf-8")
    print(f"wrote {OUT}")
